#!/bin/bash
# ============================================================
# Project EasyAI - 一键启动脚本 (Linux/macOS)
# ============================================================

set -e

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$SCRIPT_DIR"

echo "============================================================"
echo "  Project EasyAI - 一键启动脚本 (Linux/macOS)"
echo "============================================================"
echo

# ============================================================
# 1. 检查 Python 环境
# ============================================================
if ! command -v python3 &> /dev/null; then
    echo "[错误] 未找到 python3，请先安装 Python 3.10+"
    exit 1
fi

# ============================================================
# 2. 检查并安装依赖
# ============================================================
echo "[1/3] 检查 Python 依赖..."
if ! python3 -c "import websockets, aiohttp, rich, prompt_toolkit" 2>/dev/null; then
    echo "[1/3] 正在安装依赖包..."
    pip3 install -r "$SCRIPT_DIR/requirements.txt"
else
    echo "[1/3] 依赖已就绪"
fi

# ============================================================
# 3. 检查日志目录
# ============================================================
mkdir -p "$SCRIPT_DIR/logs"

# ============================================================
# 4. 启动 Python 后端
# ============================================================
echo "[2/3] 启动 Project EasyAI AI 后端..."
echo "[3/3] WebSocket 服务器将在 127.0.0.1:8765 监听"
echo
echo "============================================================"
echo "  请在启动器中启动加载了 EasyAI Mod 的 Minecraft 客户端"
echo "  日志栏将显示 '[系统] 本地端口8765握手成功，AI实体已注入'"
echo "============================================================"
echo

python3 "$SCRIPT_DIR/python/main.py"
