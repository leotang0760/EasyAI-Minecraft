package baritone.api.pathing.calc;

// ============================================================
// IPathingBehavior - 路径计算行为接口（桩代码）
// ============================================================
// 查询当前路径计算状态，支持取消路径。
// ============================================================

public interface IPathingBehavior {

    /**
     * 是否正在寻路中
     */
    boolean isPathing();

    /**
     * 取消所有寻路和路径计算任务
     */
    void cancelEverything();
}
